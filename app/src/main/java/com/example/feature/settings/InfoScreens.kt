@Composable
fun SourceCard(
    title: String,
    publisher: String,
    license: String,
    description: String
) {
    Card(
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
        modifier = Modifier.fillMaxWidth()
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Text(text = title, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, color = DeepEmerald)
            Spacer(modifier = Modifier.height(2.dp))
            Text(text = "$publisher • $license", style = MaterialTheme.typography.labelSmall, color = ForestGreen, fontWeight = FontWeight.SemiBold)
            Spacer(modifier = Modifier.height(6.dp))
            Text(text = description, style = MaterialTheme.typography.bodySmall, color = SecondaryGrey)
        }
    }
}

